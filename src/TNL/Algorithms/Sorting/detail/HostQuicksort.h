#pragma once

#include <algorithm>
#include <type_traits>
#include <utility>

#include <TNL/Devices/Host.h>
#include <TNL/Devices/Sequential.h>

#ifdef HAVE_OPENMP
   #include <omp.h>
#endif

namespace TNL::Algorithms::Sorting::detail {

/**
 * \brief Parallel quicksort implementation for the host and sequential devices.
 *
 * The algorithm is a three-way quicksort (elements lower, equal and greater
 * than the pivot), so inputs with many duplicate values do not degrade to
 * quadratic time. Ranges shorter than \ref serialThreshold are sorted by
 * `std::sort`, which avoids the recursion overhead for the many small ranges
 * generated by the partitioning.
 *
 * On \ref Devices::Host the partitioning recurses into one task for the
 * smaller part while the larger part is processed in the same task, which
 * bounds the number of tasks to one per level and keeps the recursion
 * tail-call-like. The tasks are OpenMP tasks, so the implementation is
 * serial when TNL was built without OpenMP or when the OpenMP threads are
 * disabled at runtime.
 */
template< typename Value, typename Device, typename Index >
struct HostQuicksort
{
   static_assert(
      std::is_same_v< Device, Devices::Host > || std::is_same_v< Device, Devices::Sequential >,
      "HostQuicksort supports only the Host and Sequential devices" );

   /// Ranges up to this size are sorted by std::sort.
   static constexpr Index serialThreshold = 1024;

   /**
    * \brief Returns the median of three values according to `compare`.
    */
   template< typename Compare >
   static Value&
   medianOfThree( Value& a, Value& b, Value& c, const Compare& compare )
   {
      if( compare( a, b ) ) {
         if( compare( b, c ) )
            return b;
         return compare( a, c ) ? c : a;
      }
      if( compare( a, c ) )
         return a;
      return compare( b, c ) ? c : b;
   }

   /**
    * \brief Three-way partition of `data[0, size)` around `pivot`, in place.
    *
    * Returns the half-open range `[lessEnd, greaterBegin)` occupied by the
    * elements equal to the pivot.
    */
   template< typename Compare >
   static std::pair< Index, Index >
   partition3Way( Value* data, Index size, const Value& pivot, const Compare& compare )
   {
      Index less = 0;
      Index current = 0;
      Index greater = size;
      while( current < greater ) {
         const Value& value = data[ current ];
         if( compare( value, pivot ) ) {
            std::swap( data[ less ], data[ current ] );
            ++less;
            ++current;
         }
         else if( compare( pivot, value ) ) {
            --greater;
            std::swap( data[ current ], data[ greater ] );
         }
         else {
            ++current;
         }
      }
      return { less, greater };
   }

   /**
    * \brief Sorts `data[0, size)` sequentially.
    */
   template< typename Compare >
   static void
   serialSort( Value* data, Index size, const Compare& compare )
   {
      while( size > serialThreshold ) {
         const Value pivot = medianOfThree( data[ 0 ], data[ size / 2 ], data[ size - 1 ], compare );
         const auto equal = partition3Way( data, size, pivot, compare );
         const Index lessSize = equal.first;
         const Index greaterSize = size - equal.second;
         if( lessSize + greaterSize == 0 )  // all elements are equal to the pivot
            return;
         if( lessSize < greaterSize ) {
            serialSort( data, lessSize, compare );
            data += equal.second;
            size = greaterSize;
         }
         else {
            serialSort( data + equal.second, greaterSize, compare );
            size = lessSize;
         }
      }
      std::sort( data, data + size, compare );
   }

#ifdef HAVE_OPENMP
   /**
    * \brief Sorts `data[0, size)` using OpenMP tasks; must be called from a parallel region.
    */
   template< typename Compare >
   static void
   parallelSortTask( Value* data, Index size, const Compare& compare )
   {
      while( size > serialThreshold ) {
         const Value pivot = medianOfThree( data[ 0 ], data[ size / 2 ], data[ size - 1 ], compare );
         const auto equal = partition3Way( data, size, pivot, compare );
         const Index lessSize = equal.first;
         const Index greaterSize = size - equal.second;
         if( lessSize + greaterSize == 0 )  // all elements are equal to the pivot
            return;

         // recurse into the smaller part as a task and continue with the larger
         // part here, so the number of tasks grows with the depth only
         Value* smallerData;
         Index smallerSize;
         Value* largerData;
         Index largerSize;
         if( lessSize < greaterSize ) {
            smallerData = data;
            smallerSize = lessSize;
            largerData = data + equal.second;
            largerSize = greaterSize;
         }
         else {
            smallerData = data + equal.second;
            smallerSize = greaterSize;
            largerData = data;
            largerSize = lessSize;
         }
         if( smallerSize > 0 ) {
            #pragma omp task firstprivate( smallerData, smallerSize ) shared( compare )
            parallelSortTask( smallerData, smallerSize, compare );
         }
         data = largerData;
         size = largerSize;
      }
      std::sort( data, data + size, compare );
   }
#endif

   template< typename Array, typename Compare >
   static void
   sort( Array& array, const Compare& compare )
   {
      Value* data = array.getData();
      const Index size = static_cast< Index >( array.getSize() );
      if( size < 2 )
         return;

#ifdef HAVE_OPENMP
      if( std::is_same_v< Device, Devices::Host > && Devices::Host::isOMPEnabled() ) {
         #pragma omp parallel
         {
            #pragma omp single nowait
            parallelSortTask( data, size, compare );
         }
         return;
      }
#endif
      serialSort( data, size, compare );
   }
};

}  // namespace TNL::Algorithms::Sorting::detail
